def page(name: str, title: str, sub: str, body: str) -> Path:
    HTML.mkdir(parents=True, exist_ok=True)
    f = HTML / f"{name}.html"
    f.write_text(f"<!doctype html><meta charset=utf-8><title>{html.escape(title)}</title><style>{CSS}</style>"
                 f"<div class=wrap><h1>{html.escape(title)}</h1><p class=sub>{sub}</p>{body}"
                 "<p class=foot>MIZAN-KSA | synthetic data, fixed seed 20261112 | generated by "
                 "scripts/build_artifacts.py</p></div>", encoding="utf-8")
    return f


def esc(v) -> str:
    return html.escape("" if v is None else str(v))


def pill(state: str) -> str:
    cls = {"REPORTED": "p-ok", "CLEARED": "p-ok", "PASS": "p-ok", "ACTIVE": "p-ok", "MERGE": "p-ok",
           "CONFIRMED_REJECTION": "p-bad", "UNKNOWN_OUTCOME": "p-warn", "SHREDDED": "p-bad", "OPEN": "p-warn",
           "LEGAL_HOLD_RETAINED": "p-n", "FAIL": "p-bad", "RETIRED": "p-n"}.get(state, "p-n")
    return f'<span class="pill {cls}">{esc(state)}</span>'


def table(headers: list[str], rows: list[list], num: set[int] = frozenset()) -> str:
    h = "".join(f"<th>{esc(x)}</th>" for x in headers)
    body = "".join("<tr>" + "".join(f'<td class="{"num" if i in num else ""}">{c}</td>'
                                    for i, c in enumerate(r)) + "</tr>" for r in rows)
    return f"<table><tr>{h}</tr>{body}</table>"


def kpis(items: list[tuple[str, str, str]]) -> str:
    return '<div class="grid g6">' + "".join(
        f'<div class=card><div class=k>{esc(k)}</div><div class="v {c}">{esc(v)}</div></div>' for k, v, c in items) \
        + "</div>"


