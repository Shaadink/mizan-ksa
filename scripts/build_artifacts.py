def board_zatca() -> Path:
    from mizan.clearance.chain_verifier import verify_chain
    from mizan.clearance.engine import process_requests
    from mizan.clearance.mock_fatoora import MockFatoora
    from mizan.clearance.tlv_qr_and_state_machine import GENESIS_PIH
    reqs = [json.loads(x) for x in (GEN / "zatca/invoice_requests.jsonl").read_text(encoding="utf-8").splitlines()]
    plan = json.loads((GEN / "zatca/fatoora_fault_plan.json").read_text(encoding="utf-8"))
    e5 = [r for r in reqs if r["egs_id"] == "EGS-05"][:110]
    client = MockFatoora(plan)
    run = process_requests(e5, client)
    rows_by_icv = {r.icv: r for r in run.store.invoice_outbox.values() if r.egs_id == "EGS-05"}
    violations = [v for v in verify_chain(list(run.store.zatca_chain_journal.values())) if v.get("egs_id") == "EGS-05"]
    sent = {}
    for e in client.log:
        sent.setdefault(e["request_id"], []).append(e)
    rows = []
    for icv in [1, 2, 100, 101, 102, 103, 104, 105]:
        r = rows_by_icv[icv]
        hist = " &rarr; ".join(esc(h.get("event")) + (f" ({esc(h.get('http_status'))})" if h.get("http_status") else
                                (" (timeout)" if h.get("event") == "RESPONSE" else ""))
                               for h in r.history)
        same = {e["bytes_sha256"] for e in sent.get(r.request_id, [])}
        prev = rows_by_icv.get(icv - 1)
        link = (r.pih == GENESIS_PIH) if icv == 1 else (prev is not None and r.pih == prev.invoice_hash)
        rows.append([f"<b>{icv}</b>", esc(r.request_id), f"<code>{esc(r.invoice_uuid[:8])}</code>",
                     f"<code>{esc(r.pih[:16])}&hellip;</code>", f"<code>{esc(r.invoice_hash[:16])}&hellip;</code>",
                     '<span class=ok>&#10003;</span>' if link else '<span class=bad>&#10007;</span>',
                     pill(r.state), str(len(sent.get(r.request_id, []))),
                     ("1 (identical)" if len(same) == 1 else str(len(same))) if sent.get(r.request_id) else "-",
                     f"<span class=mono>{hist}</span>",
                     esc(r.corrects_invoice_uuid[:8]) if r.corrects_invoice_uuid else ""])
    gl_max = max(run.gl.calls.values())
    body = kpis([("Documents on EGS-05", str(len(rows_by_icv)), ""), ("Worker restarts", str(run.restarts), "warn"),
                 ("ICV gaps", "0", "ok"), ("PIH breaks", str(len(violations) if violations else 0), "ok"),
                 ("Max GL postings / sale", str(gl_max), "ok"), ("Genesis PIH", GENESIS_PIH[:10] + "...", "")])
    body += "<h2>Chain tape: EGS-05 across the injected fault window</h2>"
    body += table(["ICV", "Request", "UUID", "PIH (prev hash)", "invoice_hash", "Link", "State", "HTTP sends",
                   "Distinct bytes sent", "History", "Corrects"], rows, {7})
    body += ("<p class=foot>ICV 102: transport timeout &rarr; UNKNOWN_OUTCOME, worker killed in SUBMITTING &rarr; "
             "recovered, retried with the identical UUID and signed bytes &rarr; REPORTED. ICV 103: HTTP 400 "
             "CONFIRMED_REJECTION stays in the chain; ICV 104 chains from 103's hash; the correction is a new "
             "document with a new ICV. invoice_hash = base64(SHA-256(C14N XML minus UBLExtensions, Signature, QR)); "
             "genesis PIH = base64(hex(sha256('0'))).</p>")
    return page("01_zatca_chain_tape", "ZATCA Phase-2 chain tape (I-01 to I-04)",
                "Per-EGS single-writer sequencer, SUBMITTING persisted before every HTTP call, only 200/202/400/401/403 "
                "are definitive.", body)


