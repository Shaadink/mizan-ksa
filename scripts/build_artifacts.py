def scratch_lake(name: str) -> Path:
    dst = SCRATCH / name
    shutil.rmtree(dst, ignore_errors=True)
    shutil.copytree(REPO / "data" / "lake", dst)
    return dst


def board_recon(spark, keys) -> Path:
    import subprocess

    import duckdb

    from mizan.spark import contracts as C
    from mizan.spark.bronze import land_files
    from mizan.spark.lake import Lake, cleanup_staging
    from mizan.spark.session import TableLocator
    from mizan.spark.silver import build_erp_gl_journal_lines, build_settlement_lines
    main = REPO / "tmp" / "mizan_gold.duckdb"
    q = lambda db, sql: duckdb.connect(db.as_posix(), read_only=True).execute(sql).fetchall()  # noqa: E731
    (rows, cap, ref, fees, paid, transit, quar, gl, bv, gv, unc), = q(main, """
        SELECT COUNT(*), SUM(gross_captures_sar), SUM(refunds_and_disputes_sar), SUM(acquirer_fees_sar),
               SUM(bank_paid_sar), SUM(in_transit_sar), SUM(quarantined_sar), SUM(gl_card_clearing_sar),
               SUM(ABS(unexplained_bank_variance_sar)), SUM(ABS(unexplained_gl_variance_sar)), SUM(unclassified_events)
        FROM gld.fact_merchant_settlement_recon""")
    top = q(main, """SELECT merchant_id, CAST(business_date_ksa AS VARCHAR), gross_captures_sar, refunds_and_disputes_sar,
                            acquirer_fees_sar, expected_net_payable_sar, bank_paid_sar, in_transit_sar,
                            gl_card_clearing_sar, unexplained_bank_variance_sar, unexplained_gl_variance_sar
                     FROM gld.fact_merchant_settlement_recon ORDER BY gross_captures_sar DESC LIMIT 8""")
    # demo overlay on a scratch copy: orphan bank line + 0.01 float-drift GL line
    root = scratch_lake("lake_demo")
    lk = Lake(spark, TableLocator("local", root))
    land_files(lk, keys, C.SETTLEMENT, [GEN / "demo/settlement_demo_orphan.csv"], GEN)
    land_files(lk, keys, C.ERP_GL, [GEN / "demo/erp_gl_demo_float_bug.csv"], GEN)
    build_settlement_lines(lk, GEN)
    build_erp_gl_journal_lines(lk, GEN)
    cleanup_staging(spark)
    demo_db = SCRATCH / "gold_demo.duckdb"
    demo_db.unlink(missing_ok=True)
    env = {**os.environ, "MIZAN_LAKE_ROOT": root.as_posix(), "MIZAN_DUCKDB_PATH": demo_db.as_posix(),
           "MIZAN_DBT_TARGET": "duckdb"}
    r = subprocess.run([str(REPO / ".venv/Scripts/dbt.exe"), "build", "--project-dir", str(REPO / "dbt"),  # noqa: S603
                        "--profiles-dir", str(REPO / "dbt"), "--target-path", str(SCRATCH / "dbt_t"),
                        "--log-path", str(SCRATCH / "dbt_l")], capture_output=True, text=True, env=env)
    breaker = [ln for ln in r.stdout.splitlines() if "assert_zero_unexplained_halala_variance" in ln and
               ("FAIL" in ln or "PASS" in ln)]
    breaks = q(demo_db, """SELECT merchant_id, CAST(business_date_ksa AS VARCHAR), unexplained_bank_variance_sar,
                                  unexplained_gl_variance_sar FROM gld.fact_merchant_settlement_recon
                           WHERE unexplained_bank_variance_sar <> 0 OR unexplained_gl_variance_sar <> 0""")
    f2 = lambda x: f"{x:,.2f}"  # noqa: E731
    body = kpis([("MID x day rows", f"{rows:,}", ""), ("Gross captures SAR", f2(cap), ""),
                 ("Bank paid + in transit", f2(paid + transit), ""), ("GL card clearing SAR", f2(gl), ""),
                 ("Unexplained bank variance", f2(bv), "ok"), ("Unexplained GL variance", f2(gv), "ok")])
    body += "<h2>Main build: every halala explained (largest MID-days)</h2>"
    body += table(["MID", "Business day (KSA)", "Captures", "Refunds+CB", "MDR+VAT fees", "Expected net",
                   "Bank paid", "In transit", "GL clearing", "Bank var.", "GL var."],
                  [[esc(r[0]), esc(r[1])] + [f2(x) for x in r[2:]] for r in top], set(range(2, 11)))
    body += (f"<p class=foot>Refunds and chargebacks {f2(ref)} | fees {f2(fees)} | quarantined {f2(quar)} | "
             f"unclassified events {unc}. Identity per row: expected net = bank paid + in transit + quarantined, and "
             "net sales = GL card clearing. All amounts DECIMAL(18,2).</p>")
    body += "<h2>Demo flag: seeded orphan settlement line + 0.01 SAR float bug</h2>"
    body += table(["MID", "Business day", "Unexplained bank variance", "Unexplained GL variance"],
                  [[esc(b[0]), esc(b[1]), f'<span class="{"bad" if b[2] else ""}">{f2(b[2])}</span>',
                    f'<span class="{"bad" if b[3] else ""}">{f2(b[3])}</span>'] for b in breaks], {2, 3})
    body += (f"<p class=foot>dbt circuit breaker on the demo build: "
             f"{'FAIL (as designed)' if any('FAIL' in b for b in breaker) else esc(breaker)}; the main build passes. "
             "The demo overlay never enters the main build.</p>")
    return page("02_halala_recon_board", "Halala reconciliation board (I-05, I-06)",
                "gld.fact_merchant_settlement_recon: POS captures vs mada/SADAD settlement vs ERP card clearing, "
                "MID x business day, key spine across all three legs.", body)


def board_pdpl(spark, keys) -> Path:
    import csv

    from pyspark.sql import functions as F

    from mizan.privacy import crypto
    from mizan.privacy.pdpl import execute_dsr, restore_guard
    from mizan.spark.lake import Lake, cleanup_staging
    from mizan.spark.session import TableLocator
    root = scratch_lake("lake_pdpl")
    lk = Lake(spark, TableLocator("local", root))
    pos = list(csv.DictReader((GEN / "crm/crm_pos_cp1256.csv").open(encoding="cp1256", newline="")))
    token = crypto.token_for(keys.hmac_key, pos[0]["source_customer_id"])
    g = next(r for r in lk.read("slv", "golden_party_scd2").filter("is_current AND status = 'ACTIVE'").collect()
             if token in json.loads(r["member_tokens"]))
    toks = sorted(json.loads(g["member_tokens"]))
    vault = lambda: {r["subject_token_id"]: r for r in lk.read("security", "pii_vault_metadata")  # noqa: E731
                     .filter(F.col("subject_token_id").isin(*toks)).collect()}
    src = g["name_ar_source_token"]
    v1 = vault()
    name = crypto.decrypt_field(crypto.unwrap_dek(keys, src, bytes(v1[src]["wrapped_dek"])), src, "full_name_ar",
                                g["name_ar_enc"])
    links1 = lk.read("security", "subject_token_map").filter(F.col("subject_token_id").isin(*toks)).count()
    golden_version = spark.sql(f"DESCRIBE HISTORY {lk.ref('slv', 'golden_party_scd2')}").agg({"version": "max"}) \
        .first()[0]
    backup = SCRATCH / "vault_backup"
    shutil.rmtree(backup, ignore_errors=True)
    shutil.copytree(lk.path("security", "pii_vault_metadata"), backup)
    ev = execute_dsr(lk, keys, national_id=pos[0]["national_id"], requested_by="dpo@najd.example")
    v2 = vault()
    try:
        crypto.unwrap_dek(keys, src, v2[src]["wrapped_dek"])
        after_name = "DECRYPTED (unexpected)"
    except PermissionError:
        after_name = "PermissionError: DEK for this subject has been shredded"
    links2 = lk.read("security", "subject_token_map").filter(F.col("subject_token_id").isin(*toks)).count()
    vp = lk.path("security", "pii_vault_metadata")
    shutil.rmtree(vp)
    shutil.copytree(backup, vp)
    spark.sql(f"RESTORE TABLE {lk.ref('slv', 'golden_party_scd2')} TO VERSION AS OF {golden_version}")
    restored_keys = sum(1 for r in vault().values() if r["wrapped_dek"] is not None)
    rep = restore_guard(lk, keys)
    v3 = vault()
    cleanup_staging(spark)
    p1 = table(["Field", "Value"], [["Golden id", f"<code>{esc(g['golden_id'])}</code>"],
                                     ["Linked records", str(len(toks))],
                                     ["Vault DEKs", " ".join(pill(r["dek_status"]) for r in v1.values())],
                                     ["Legal name (decrypted)", f'<span dir=rtl style="font-size:18px">{esc(name)}</span>'],
                                     ["Token &rarr; identity links", str(links1)]])
    p2 = table(["Field", "Value"], [["DSR", f"<code>{esc(ev['dsr_id'])}</code> by {esc(ev['requested_by'])}"],
                                     ["Vault wrapped_dek", "NULL x" + str(sum(1 for r in v2.values()
                                                                                if r["wrapped_dek"] is None))],
                                     ["Vault status", " ".join(pill(r["dek_status"]) for r in v2.values())],
                                     ["Analytic name", f'<span class=bad>{esc(after_name)}</span>'],
                                     ["Token &rarr; identity links", f"{links2} (removed {ev['token_links_removed']})"],
                                     ["Signed tax journal", pill(ev["signed_tax_invoice_status"]) +
                                      f" ({ev['journal_rows_retained']} rows kept)"],
                                     ["Tax totals before", f"<code>{esc(ev['tax_totals_before'])}</code>"],
                                     ["Tax totals after", f"<code>{esc(ev['tax_totals_after'])}</code>"]])
    p3 = table(["Step", "Result"], [["Restore pre-erasure vault backup + RESTORE Silver golden table",
                                     f"<span class=warn>{restored_keys} keys back in the vault</span>"],
                                    ["Restore Guard re-applies tombstones", f"re-shredded {rep['keys_reshredded']}, "
                                     f"re-resolved {rep['goldens_reresolved']} golden profile(s)"],
                                    ["Vault after guard", " ".join(pill(r["dek_status"]) for r in v3.values())],
                                    ["Vault time travel to old version", "files VACUUMed (RETAIN 0 HOURS)"]])
    body = (f'<div class="grid g3"><div><h2>1. Before: live key, readable name</h2>{p1}</div>'
            f"<div><h2>2. After DSR: crypto-shredded, tax evidence kept</h2>{p2}</div>"
            f"<div><h2>3. Restore attempt: blocked by the guard</h2>{p3}</div></div>")
    return page("03_pdpl_shred_restore", "PDPL erasure with legal hold and Restore Guard (I-07, I-08)",
                "Encrypt at the Bronze write; erasure destroys every linked per-subject key, removes the token link, "
                "keeps the signed ZATCA journal, and survives a restore of data AND vault.", body)


def board_mdm(spark, keys) -> Path:
    import csv

    from mizan.ingest.cp1256 import repair_text
    from mizan.mdm.arabic_norm_and_privacy import build_arabic_search_key
    from mizan.privacy import crypto
    from mizan.spark.lake import Lake
    from mizan.spark.session import TableLocator
    lk = Lake(spark, TableLocator("local", REPO / "data" / "lake"))
    man = {d["id"]: d["location"] for d in json.loads((GEN / "defect_manifest.json").read_text(encoding="utf-8"))
           ["defects"]}
    raw = {r["source_customer_id"]: r for r in
           list(csv.DictReader((GEN / "crm/crm_pos_cp1256.csv").open(encoding="cp1256", newline="")))
           + list(csv.DictReader((GEN / "crm/crm_ecom_utf8.csv").open(encoding="utf-8", newline="")))}
    tok = {crypto.token_for(keys.hmac_key, s): s for s in raw}
    goldens = {}
    for g in lk.read("slv", "golden_party_scd2").filter("is_current AND status = 'ACTIVE'").collect():
        for t in json.loads(g["member_tokens"]):
            goldens[tok.get(t)] = g
    ledger = {r["subject_token_id"]: r.asDict() for r in lk.read("slv", "entity_merge_ledger").collect()}
    rows = []
    for sid in man["D11"]["ids"]:
        r = raw[sid]
        g = goldens.get(sid)
        shown = r["full_name_ar"] or r["full_name_en"]
        repaired, status = repair_text(r["full_name_ar"]) if r["full_name_ar"] else (r["full_name_en"], "CLEAN")
        rule = ledger.get(crypto.token_for(keys.hmac_key, sid), {}).get("match_rule", "")
        rows.append([esc(sid), f'<span dir=auto style="font-size:15px">{esc(shown)}</span>',
                     f'<span dir=auto style="font-size:15px">{esc(repaired)}</span> ' +
                     (pill("REPAIRED") if status == "REPAIRED_MOJIBAKE" else ""),
                     f"<code>{esc(r['national_id'])}</code>",
                     f'<span dir=auto>{esc(build_arabic_search_key(repaired))}</span>',
                     f"<code>{esc(g['golden_id'] if g else '-')}</code>", pill("MERGE"), esc(rule)])
    brows = []
    d10 = man["D10"]
    for sid in [*d10["brothers"], d10["id_less_third"]]:
        r = raw[sid]
        g = goldens.get(sid)
        brows.append([esc(sid), f'<span dir=auto>{esc(r["full_name_ar"])}</span>', esc(r["full_name_en"]),
                      f"<code>{esc(r['national_id'] or '(none)')}</code>", f"<code>{esc(r['landline'])}</code>",
                      f"<code>{esc(g['golden_id'])}</code>" if g else pill("OPEN") + " steward queue"])
    c = lk.read("quarantine", "mdm_match_conflicts").first()
    body = "<h2>Five surface spellings &rarr; one golden id (checksum-valid ID anchor)</h2>"
    body += table(["Source record", "Name as received", "Repaired at Bronze", "ID as received",
                   "Search key (lossy, blocking only)",
                   "Golden id", "Action", "Rule"], rows)
    body += "<h2>Hard-negative brother test</h2>"
    body += table(["Source record", "Arabic name", "English name", "National ID", "Landline", "Outcome"], brows)
    body += (f"<p class=foot>Brothers share father's name, family name and landline but hold different valid IDs: "
             f"never merged. The ID-less third record matches both on name + landline &rarr; "
             f"quarantine.mdm_match_conflicts ({esc(c['conflict_type'])}, {esc(c['status'])}), never auto-merged. "
             "Every merge is an append-only event in slv.entity_merge_ledger and reversible by UNMERGE. Silver keeps "
             "names only as ciphertext and IDs/phones as keyed HMACs; this board decrypts synthetic data.</p>")
    return page("04_arabic_mdm_board", "Bilingual Arabic MDM (I-09, I-10)",
                "CP1256 repair, NFKC ligature folding, Arabic-Indic digits, typed identifier registry; deterministic "
                "ladder with a steward queue instead of fuzzy guesses.", body)


